"""Расчёт коэффициентов МНК для набора измерений x и y."""

import numpy as np


def mnk(x, y):
    """Вернуть коэффициенты линейной регрессии y = a + b*x.

    Аргументы:
        x: Массив значений x (независимая переменная).
        y: Массив значений y (зависимая переменная).

    Возвращает:
        Кортеж (a, b): свободный член и наклон прямой.
    """
    # Приводим входные данные к массивам NumPy
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    n = len(x)

    # Суммы, необходимые для формул МНК
    s_x = x.sum()
    s_y = y.sum()
    s_xx = (x * x).sum()
    s_xy = (x * y).sum()

    # Средние значения
    x_mean = s_x / n
    y_mean = s_y / n

    # Знаменатель формулы наклона
    d = n * s_xx - s_x * s_x

    # Наклон и свободный член
    b = (n * s_xy - s_x * s_y) / d
    a = y_mean - b * x_mean

    return a, b