"""Вывод треугольника заданного размера заданным символом."""


def triangle(size, symb, i=1):
    """Рекурсивно напечатать треугольник.

    Переменные:
        size: Количество строк.
        symb: Символ, которым заполняется треугольник.
        i: Номер текущей строки (начинается с 1).
    """
    # База рекурсии: строки закончились
    if i > size//2 + 1:
        return

    # Прямой ход: печатаем растущие строки
    print(symb * i)
    triangle(size, symb, i + 1)

    # Обратный ход: печатаем убывающие строки
    if i < size//2 + 1:
        print(symb * i)


triangle(5, 'c')