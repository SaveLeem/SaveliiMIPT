"""Вывод N-го числа Фибоначчи с помощью рекурсии."""


def fib(n):
    """Вернуть N-е число Фибоначчи.

    Аргументы:
        n: Индекс числа Фибоначчи (нумерация с 0).

    Возвращает:
        N-е число Фибоначчи.
    """
    # Базовые случаи
    if n == 0:
        return 0
    if n == 1:
        return 1
    # Рекурсивный шаг: сумма двух предыдущих
    return fib(n - 1) + fib(n - 2)


n = int(input())
print(fib(n))