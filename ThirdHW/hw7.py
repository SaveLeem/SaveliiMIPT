"""Решение системы линейных уравнений методом Крамера."""

import numpy as np

# спрашиваем размер системы
N = int(input("Размер системы: "))

# в расширенной матрице на один столбец больше
M = N + 1

# создаём пустую матрицу из нулей
matrix = np.zeros((N, M))

# построчно заполняем матрицу
for i in range(N):
    row = input(f"Введите строку номером {i}: ")
    matrix[i, :] = list(map(float, row.split()))

# отделяем коэффициенты от свободных членов
A = matrix[:, :-1]
b = matrix[:, -1]

# считаем главный определитель
det_main = np.linalg.det(A)

# тут будем хранить определители с заменённым столбцом
dets = [0] * N

# для каждой переменной заменяем её столбец на b
for i in range(N):
    Ai = A.copy()
    Ai[:, i] = b
    dets[i] = np.linalg.det(Ai)

# считаем сами неизвестные
x = np.zeros(N)
for i in range(N):
    x[i] = dets[i] / det_main

# выводим ответ
print("Решение:", x)
