"""Вывод разложения числа на простые множители."""


def factorize(n, factors=None):
    """Вернуть список простых множителей числа n.

    Аргументы:
        n: Число, которое нужно разложить.
        factors: Накопитель для рекурсии (вручную не передавать).

    Возвращает:
        Список простых множителей по возрастанию.
    """
    # Создаём список только при первом вызове,
    # чтобы не использовать изменяемое значение по умолчанию
    if factors is None:
        factors = []

    # База рекурсии: дошли до 1 — все множители собраны
    if n == 1:
        return factors

    # Ищем наименьший делитель
    for i in range(2, n + 1):
        if n % i == 0:
            factors.append(i)
            # Делим число и продолжаем разложение
            return factorize(n // i, factors)

    return factors


